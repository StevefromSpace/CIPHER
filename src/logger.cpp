#include <chrono>
#include <ctime>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <string>

// ---------------------------------------------------------------------------
// logger.cpp  —  Implementation of the Logger
//
// Reading guide for a C++ learner:
//
//  std::ofstream is a "file output stream" — it writes text to a file.
//  When we open it in the constructor with ios::app, new lines are appended
//  to the end of the file rather than overwriting it.  This means multiple
//  CIPHER sessions accumulate in the same log file.
//
//  The formatted log line looks like:
//    2026-10-15 13:00:00 [INFO ] CIPHER started
//
//  The timestamp is generated by current_utc_time() using the same
//  platform-safe localtime helper pattern used in cipher_core.cpp.
// ---------------------------------------------------------------------------

namespace cipher {
namespace {

// ---------------------------------------------------------------------------
// current_local_time
// Returns the local wall-clock time formatted as "YYYY-MM-DD HH:MM:SS".
// Uses the same platform-safe approach as cipher_core.cpp.
// ---------------------------------------------------------------------------
std::string current_local_time() {
    const auto now = std::chrono::system_clock::now();
    const std::time_t t = std::chrono::system_clock::to_time_t(now);
    std::tm local_tm{};

#if defined(_WIN32)
    if (localtime_s(&local_tm, &t) != 0) {
        return "????-??-?? ??:??:??";
    }
#else
    if (localtime_r(&t, &local_tm) == nullptr) {
        return "????-??-?? ??:??:??";
    }
#endif

    std::ostringstream out;
    out << std::put_time(&local_tm, "%Y-%m-%d %H:%M:%S");
    return out.str();
}

// ---------------------------------------------------------------------------
// level_label
// Returns a fixed-width 5-character label for a log level, e.g. "INFO ".
// The padding keeps log lines column-aligned and easier to read.
// ---------------------------------------------------------------------------
const char* level_label(LogLevel level) noexcept {
    switch (level) {
        case LogLevel::DEBUG: return "DEBUG";
        case LogLevel::INFO:  return "INFO ";
        case LogLevel::WARN:  return "WARN ";
        case LogLevel::ERROR: return "ERROR";
    }
    return "INFO ";
}

// ---------------------------------------------------------------------------
// format_line
// Builds the complete log line string.
// ---------------------------------------------------------------------------
std::string format_line(LogLevel level, const std::string& message) {
    std::ostringstream out;
    out << current_local_time()
        << " [" << level_label(level) << "] "
        << message;
    return out.str();
}

} // namespace

// ---------------------------------------------------------------------------
// Logger constructor
// ---------------------------------------------------------------------------
Logger::Logger(LogLevel minimum_level, const std::string& log_file_path)
    : minimum_level_(minimum_level)
    , log_file_path_(log_file_path)
{
    if (!log_file_path_.empty()) {
        // Open in append mode so we don't destroy previous session logs.
        file_.open(log_file_path_, std::ios::app);
        if (!file_.is_open()) {
            // Report the problem to stderr and continue with stderr-only
            // logging.  The application remains functional.
            std::cerr << current_local_time()
                      << " [WARN ] Could not open log file '"
                      << log_file_path_
                      << "'; using stderr only.\n";
            log_file_path_.clear(); // Reflect that file logging is disabled.
        }
    }
}

// ---------------------------------------------------------------------------
// Logging convenience methods
// ---------------------------------------------------------------------------
void Logger::debug(const std::string& message) { log(LogLevel::DEBUG, message); }
void Logger::info (const std::string& message) { log(LogLevel::INFO,  message); }
void Logger::warn (const std::string& message) { log(LogLevel::WARN,  message); }
void Logger::error(const std::string& message) { log(LogLevel::ERROR, message); }

void Logger::log(LogLevel level, const std::string& message) {
    // Discard messages below the configured minimum level.
    if (static_cast<int>(level) < static_cast<int>(minimum_level_)) {
        return;
    }
    emit(level, message);
}

// ---------------------------------------------------------------------------
// emit — writes the formatted line to the active output destination(s)
// ---------------------------------------------------------------------------
void Logger::emit(LogLevel level, const std::string& message) {
    const std::string line = format_line(level, message);

    // Always write to stderr.
    std::cerr << line << '\n';

    // Also write to the log file if one is open.
    if (file_.is_open()) {
        file_ << line << '\n';
        // flush() ensures the line reaches disk even if the program exits
        // unexpectedly.  For low-volume diagnostic logging the performance
        // cost is acceptable.
        file_.flush();
    }
}

} // namespace cipher
